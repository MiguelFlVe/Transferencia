// Solicitar edades
let edad1 = parseInt(prompt("Ingresa la edad de la persona 1:"));
let edad2 = parseInt(prompt("Ingresa la edad de la persona 2:"));
let edad3 = parseInt(prompt("Ingresa la edad de la persona 3:"));
let edad4 = parseInt(prompt("Ingresa la edad de la persona 4:"));

// Calcular promedio
let promedio = (edad1 + edad2 + edad3 + edad4) / 4;

// Mostrar resultado en consola
console.log("El promedio de edad del grupo es: " + promedio);
